# Function to calculate RSI (Relative Strength Index)
def calculate_rsi(data, window=14):
    delta = data.diff()
    gain = (delta.where(delta > 0, 0)).rolling(window=window).mean()
    loss = (-delta.where(delta < 0, 0)).rolling(window=window).mean()
    rs = gain / loss
    return 100 - (100 / (1 + rs))

# 1. Add RSI to our Main Data
df_features = pd.DataFrame(index=df.index)
df_features['RSI'] = calculate_rsi(df['GLD'])

# 2. Add Volatility (Standard Deviation of last 20 days)
df_features['Volatility'] = df['GLD'].pct_change().rolling(window=20).std()

# 3. Add our old friends (Lagged Returns)
df_features['Gold_Lag1'] = df['GLD'].pct_change().shift(1)
df_features['Oil_Lag1'] = df['USO'].pct_change().shift(1)
df_features['Stock_Lag1'] = df['SPY'].pct_change().shift(1)

# 4. Cleanup
df_features = df_features.dropna()
y_target = df['GLD'].pct_change().loc[df_features.index]

print("New Features Created:")
print(df_features.tail())

# 1. Split again (New Data)
X_train_v2, X_test_v2, y_train_v2, y_test_v2 = train_test_split(df_features, y_target, test_size=0.2, shuffle=False)

# 2. Train the Enhanced Model
model_v2 = RandomForestRegressor(n_estimators=100, min_samples_leaf=5, random_state=42)
model_v2.fit(X_train_v2, y_train_v2)

# 3. Predict
predictions_v2 = model_v2.predict(X_test_v2)

# 4. Check Feature Importance (What does the AI care about?)
importance = pd.Series(model_v2.feature_importances_, index=df_features.columns)
importance.sort_values().plot(kind='barh', title="What drives Gold Prices?")
